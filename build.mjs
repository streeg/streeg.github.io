// Bakes the copy from content.js into static HTML: /index.html (English) and /pt/index.html (Portuguese).
// The page then reads fine without JavaScript, and crawlers, link previews and recruiting tools see the real content.
// Usage: node build.mjs        (no dependencies)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = dirname(fileURLToPath(import.meta.url));
const SITE = "https://streeg.github.io";
const PAGES = { en: { path: "/", out: "index.html", htmlLang: "en", locale: "en_US" }, pt: { path: "/pt/", out: "pt/index.html", htmlLang: "pt-BR", locale: "pt_BR" } };

const ctx = {}; ctx.window = ctx;
vm.createContext(ctx);
for (const f of ["content.js", "render.js"]) vm.runInContext(readFileSync(join(ROOT, f), "utf8"), ctx, { filename: f });
const { CONTENT, LINKS, STACK, RENDER: R } = ctx;
const template = readFileSync(join(ROOT, "src/index.html"), "utf8");

const attr = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const lookup = (c, path) => {
  const v = path.split(".").reduce((o, k) => (o == null ? o : o[k]), c);
  if (typeof v !== "string") throw new Error(`content key "${path}" is missing or not text`);
  return v;
};
function once(html, re, fn, what) {
  let n = 0;
  const out = html.replace(re, (...m) => { n++; return fn(...m); });
  if (n !== 1) throw new Error(`${what}: expected 1 match, found ${n}`);
  return out;
}
// Fill an empty element by id: <tag ... id="x" ...></tag>
const fillId = (html, id, inner) => once(html, new RegExp(`(<([a-z0-9]+)[^>]*\\sid="${id}"[^>]*>)(</\\2>)`), (_, open, _t, close) => open + inner + close, `#${id}`);
// Set an attribute inside the opening tag that carries a given marker attribute.
const setAttr = (tag, name, value) => (new RegExp(`\\s${name}="[^"]*"`).test(tag) ? tag.replace(new RegExp(`(\\s${name}=)"[^"]*"`), `$1"${attr(value)}"`) : tag.replace(/>$/, ` ${name}="${attr(value)}">`));

function build(lang) {
  const c = CONTENT[lang], page = PAGES[lang], other = PAGES[lang === "en" ? "pt" : "en"];
  let html = template.replace(/<!-- Source template\.[^>]*-->\n/, "<!-- Generated by build.mjs from src/index.html and content.js. Do not edit by hand. -->\n");

  // document language, metadata, alternates
  html = once(html, /<html lang="en"/, () => `<html lang="${page.htmlLang}"`, "html lang");
  html = once(html, /<title><\/title>/, () => `<title>${R.esc(c.meta.title)}</title>`, "title");
  html = once(html, /(<meta name="description" content=)""/, (_, a) => `${a}"${attr(c.meta.description)}"`, "description");
  html = once(html, /(<meta property="og:title" content=)""/, (_, a) => `${a}"${attr(c.meta.title)}"`, "og:title");
  html = once(html, /(<meta property="og:description" content=)""/, (_, a) => `${a}"${attr(c.meta.description)}"`, "og:description");
  html = once(html, /(<meta property="og:url" content=)""/, (_, a) => `${a}"${SITE}${page.path}"`, "og:url");
  html = once(html, /  <!--build:alternates-->/, () => [
    `  <link rel="canonical" href="${SITE}${page.path}">`,
    `  <link rel="alternate" hreflang="en" href="${SITE}/">`,
    `  <link rel="alternate" hreflang="pt-BR" href="${SITE}/pt/">`,
    `  <link rel="alternate" hreflang="x-default" href="${SITE}/">`,
    `  <meta property="og:locale" content="${page.locale}">`,
    `  <meta property="og:locale:alternate" content="${other.locale}">`,
  ].join("\n"), "alternates");

  // text, labels, alt text, placeholders, links
  html = html.replace(/(<([a-z0-9]+)\s[^>]*data-i18n="([^"]+)"[^>]*>)[^<]*(<\/\2>)/g, (_, open, _t, key, close) => open + R.esc(lookup(c, key)) + close);
  html = html.replace(/<[^>]*\sdata-i18n-aria="([^"]+)"[^>]*>/g, (tag, key) => setAttr(tag, "aria-label", lookup(c, key)));
  html = html.replace(/<[^>]*\sdata-i18n-alt="([^"]+)"[^>]*>/g, (tag, key) => setAttr(tag, "alt", lookup(c, key)));
  html = html.replace(/<[^>]*\sdata-i18n-ph="([^"]+)"[^>]*>/g, (tag, key) => setAttr(tag, "placeholder", lookup(c, key)));
  html = html.replace(/<[^>]*\sdata-link="([^"]+)"[^>]*>/g, (tag, key) => {
    if (!LINKS[key]) throw new Error(`missing link "${key}"`);
    return setAttr(tag, "href", LINKS[key]);
  });

  // generated blocks (the same builders main.js uses when the language changes)
  html = fillId(html, "impact-grid", R.impact(c));
  html = fillId(html, "jobs", R.jobs(c));
  html = fillId(html, "filters", R.filters(c));
  html = fillId(html, "stack-grid", R.stack(STACK));
  html = fillId(html, "thesis-tags", R.thesisTags(c));
  html = fillId(html, "academic", R.academic(c, LINKS));
  html = fillId(html, "typed", R.esc(c.hero.words[0]));
  html = fillId(html, "typed-sr", R.esc(R.typedSentence(c)));
  html = fillId(html, "email-link", R.esc(LINKS.email));
  html = fillId(html, "year", String(new Date().getFullYear()));

  // nothing left unfilled
  const empty = [...html.matchAll(/<([a-z0-9]+)\s[^>]*data-i18n="([^"]+)"[^>]*><\/\1>/g)].map((m) => m[2]);
  if (empty.length) throw new Error(`empty i18n nodes: ${empty.join(", ")}`);
  for (const bad of ['href=""', 'aria-label=""', 'placeholder=""', 'content=""', "undefined", "<!--build:"]) {
    if (html.includes(bad)) throw new Error(`unfilled value left in ${page.out}: ${bad}`);
  }
  mkdirSync(dirname(join(ROOT, page.out)), { recursive: true });
  writeFileSync(join(ROOT, page.out), html);
  console.log(`built ${page.out} (${(html.length / 1024).toFixed(1)} KB)`);
}

build("en");
build("pt");

writeFileSync(join(ROOT, "sitemap.xml"), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${["/", "/pt/"].map((p) => `  <url><loc>${SITE}${p}</loc><xhtml:link rel="alternate" hreflang="en" href="${SITE}/"/><xhtml:link rel="alternate" hreflang="pt-BR" href="${SITE}/pt/"/></url>`).join("\n")}
</urlset>
`);
writeFileSync(join(ROOT, "robots.txt"), `User-agent: *\nAllow: /\nSitemap: ${SITE}/sitemap.xml\n`);
console.log("built sitemap.xml, robots.txt");
